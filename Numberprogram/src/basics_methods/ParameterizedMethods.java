package basics_methods;

public class ParameterizedMethods {
//parameterizedmethod
	
	    public static void m1(int a)
		{
			System.out.println("a value is:"+a);
		}
        public static void main(String[]args)
        {
        	System.out.println("Started");
        	m1(20);
        	System.out.println("Ended");
        }
 }
	

